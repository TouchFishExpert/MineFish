import assert from 'node:assert/strict';
import {DeepSeek} from '../mindcraft/src/models/deepseek.js';
import {ModelRequestError} from '../mindcraft/src/utils/model_failure.js';
process.env.DEEPSEEK_API_KEY = 'unit-deepseek-key-123456';
const events = [], wire = [];
const completion = {id: 'complete-response', object: 'chat.completion', created: 1, model: 'deepseek-flash', choices: [{index: 0, message: {role: 'assistant', content: '你好，完整回复', reasoning_content: '完整推理字段'}, finish_reason: 'stop'}], usage: {prompt_tokens: 50, completion_tokens: 10, total_tokens: 60, prompt_cache_hit_tokens: 30}};
const response = (body, status = 200, headers = {}) => new Response(JSON.stringify(body), {status, headers: {'content-type': 'application/json', ...headers}});
let attempts = 0;
const fetch = async (url, options) => {
    wire.push({url: String(url), body: JSON.parse(options.body)}); attempts++;
    if (attempts === 1) return response({error: {message: 'temporarily unavailable unit-deepseek-key-123456'}}, 503, {'retry-after-ms': '1'});
    return response(completion);
};
const model = new DeepSeek('deepseek-flash', 'https://api.deepseek.com', {max_tokens: 2000, temperature: .6}, {fetch, publish: event => events.push(event)});
const result = await model.sendRequest([{role: 'user', content: '测试中文'}], '完整系统提示 unit-deepseek-key-123456', undefined, {purpose: 'memory'});
assert.equal(result, completion.choices[0].message.content);
assert.equal(events.length, 4); assert.equal(wire.length, 2);
assert.equal(events[0].endpoint, wire[0].url); assert.equal(events[0].request.max_tokens, 2000);
assert.match(events[0].request.messages[0].content, /完整系统提示 \[REDACTED\]/);
assert.match(wire[0].body.messages[0].content, /完整系统提示 unit-deepseek-key-123456/, 'Logging must not alter the real request');
assert.equal(events[0].purpose, 'memory'); assert.equal(events[0].operationId, events[2].operationId);
assert.notEqual(events[0].id, events[2].id); assert.equal(events[1].httpStatus, 503);
assert.equal(events[1].response.error.message.includes('unit-deepseek-key-123456'), false);
assert.deepEqual(events[3].response, completion);
assert.equal(events.some(event => JSON.stringify(event).includes('authorization')), false);
const errors = [];
const failing = new DeepSeek('deepseek-flash', 'https://api.deepseek.com', {}, {fetch: async () => {throw Error('network unavailable');}, publish: event => errors.push(event)});
await assert.rejects(failing.sendRequest([], '测试失败'), ModelRequestError);
assert.equal(errors.filter(event => event.phase === 'request').length, 2);
assert.equal(errors.filter(event => event.phase === 'error').length, 2);
const loggingFailure = new DeepSeek('deepseek-flash', 'https://api.deepseek.com', {}, {fetch: async () => response(completion), publish: () => {throw Error('disk unavailable');}});
assert.equal(await loggingFailure.sendRequest([], '日志失败不影响回复'), completion.choices[0].message.content);
console.log('PASS: actual SDK HTTP request body and complete response, concurrent-safe purpose, every transport retry with matching IDs, reasoning and usage retained, credentials removed only from logs, network failure recorded, and logging failure does not alter model behavior.');
